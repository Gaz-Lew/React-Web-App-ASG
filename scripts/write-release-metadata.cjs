const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const root = path.resolve(__dirname, "..");
const outputPath = path.join(root, "src", "generated", "releaseMetadata.ts");
const envPath = path.join(root, ".env");

function readJson(relativePath) {
  return JSON.parse(fs.readFileSync(path.join(root, relativePath), "utf8"));
}

function readDotEnv() {
  if (!fs.existsSync(envPath)) {
    return {};
  }

  return fs
    .readFileSync(envPath, "utf8")
    .split(/\r?\n/)
    .reduce((acc, line) => {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith("#")) {
        return acc;
      }

      const separatorIndex = trimmed.indexOf("=");
      if (separatorIndex === -1) {
        return acc;
      }

      const key = trimmed.slice(0, separatorIndex).trim();
      const value = trimmed.slice(separatorIndex + 1).trim().replace(/^["']|["']$/g, "");
      acc[key] = value;
      return acc;
    }, {});
}

function gitValue(args, fallback) {
  try {
    return execFileSync("git", args, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return fallback;
  }
}

function normalizeEnvironment(value) {
  const normalized = String(value || "").trim().toLowerCase();
  if (["development", "dev", "local"].includes(normalized)) {
    return "development";
  }
  if (normalized === "staging") {
    return "staging";
  }
  if (["production", "prod"].includes(normalized)) {
    return "production";
  }
  return "unknown";
}

const packageJson = readJson("package.json");
const dotEnv = readDotEnv();
const appEnv = normalizeEnvironment(process.env.VITE_APP_ENV || process.env.APP_ENV || dotEnv.VITE_APP_ENV || "production");
const commit = process.env.VITE_RELEASE_COMMIT || gitValue(["rev-parse", "--short", "HEAD"], "unknown");
const fullCommit = process.env.VITE_RELEASE_COMMIT_FULL || gitValue(["rev-parse", "HEAD"], commit);
const deployedAt = process.env.VITE_RELEASE_DEPLOYED_AT || new Date().toISOString();
const version = process.env.VITE_RELEASE_VERSION || packageJson.version || "0.0.0";
const firebaseProjectId = process.env.VITE_FIREBASE_PROJECT_ID || dotEnv.VITE_FIREBASE_PROJECT_ID || "unknown";

const metadata = {
  environment: appEnv,
  version,
  commit,
  fullCommit,
  deployedAt,
  firebaseProjectId,
};

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(
  outputPath,
  `// Generated by scripts/write-release-metadata.cjs. Do not edit by hand.
export const GENERATED_RELEASE_METADATA = ${JSON.stringify(metadata, null, 2)} as const;
`,
);

console.log(
  `Release metadata: environment=${metadata.environment} version=${metadata.version} commit=${metadata.commit} deployedAt=${metadata.deployedAt} firebaseProjectId=${metadata.firebaseProjectId}`,
);
